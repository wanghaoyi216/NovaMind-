package com.novamind.gateway.strategy;

/**
 * R26 灰度发布策略类型枚举
 *
 * <p>三种典型发布形态：</p>
 * <ul>
 *   <li>{@link #BLUE_GREEN} 蓝绿发布：两套完整环境，瞬间整体切换；故障秒级回滚</li>
 *   <li>{@link #CANARY} 金丝雀发布：渐进式 1%→5%→10%→30%→100% 阶梯放量</li>
 *   <li>{@link #AB_TEST} A/B 实验：按规则（地域/设备/版本）长期分桶对比</li>
 * </ul>
 *
 * <p><b>策略选型速查</b>：</p>
 * <pre>
 *  业务影响面大 / 上下游强耦合 / 必须整体切换   → 蓝绿
 *  新版本有未知风险 / 需要渐进观察           → 金丝雀
 *  验证新功能/新策略对核心指标的影响           → A/B
 * </pre>
 */
public enum GrayStrategyType {

    /** 蓝绿发布：瞬间 100% 切流量，秒级回滚 */
    BLUE_GREEN,

    /** 金丝雀发布：渐进式阶梯放量（1% → 5% → 10% → 30% → 100%） */
    CANARY,

    /** A/B 实验：按规则分桶（地域/设备/版本），长期共存对比 */
    AB_TEST
}
